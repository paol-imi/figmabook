import { posix } from 'node:path';
import { asSentence, escapeHtml, rebasePlanLinks, unescapeCell } from './markdown.ts';
import { type Catalog, type CatalogDomain, type CatalogRow, type CatalogSeverity, catalogRows } from './model.ts';
import { DOCS_DIR, PLAN_DIR } from './paths.ts';

export { DOCS_DIR } from './paths.ts';
export const DOCS_INDEX = 'README.md';

/** The plan folder as a relative link prefix from {@link DOCS_DIR}, e.g. `../../internal/plan/`. */
const PLAN_FROM_DOCS = `${posix.relative(DOCS_DIR, PLAN_DIR)}/`;

/**
 * Plan chapter titles, keyed by file name inside the plan folder (`05-capture.md` →
 * `Capture engine`). A chapter without a title is named by its number.
 */
export type ChapterTitles = ReadonlyMap<string, string>;

const SEVERITY_LABEL: Readonly<Record<CatalogSeverity, string>> = { info: 'info', warn: 'warning', error: 'error' };

/**
 * Renders the docs pages: `README.md`, an index with one section per domain and a stable
 * `#CODE` anchor per code, and one `<CODE>.md` page per code (what happened, what to do,
 * where it is defined; D-40). Keys are file names inside {@link DOCS_DIR}, in sorted order.
 *
 * The pages link into the internal design notes but never name their files or paths in text,
 * so a page reads the same when the site turns those links into plain text.
 */
export function renderDocs(catalog: Catalog, titles: ChapterTitles = new Map()): ReadonlyMap<string, string> {
  const pages = new Map<string, string>();
  pages.set(DOCS_INDEX, renderIndex(catalog));
  const sorted = [...catalogRows(catalog)].sort((a, b) => (a.code < b.code ? -1 : 1));
  const domains = new Map(catalog.domains.map((domain) => [domain.prefix, domain]));
  for (const row of sorted) {
    const domain = domains.get(row.domain);
    if (domain) pages.set(`${row.code}.md`, renderCodePage(row, domain, catalog.source, titles));
  }
  return pages;
}

function banner(source: string): string {
  return `<!-- Generated by tools/diag-gen from ${source}#diagnostics. Do not edit: run \`pnpm diag:gen\`. -->`;
}

/** Link from {@link DOCS_DIR} to a plan chapter. */
function planLink(file: string, anchor?: string): string {
  return `${PLAN_FROM_DOCS}${file}${anchor ? `#${anchor}` : ''}`;
}

function sourceFile(source: string): string {
  return source.slice(source.lastIndexOf('/') + 1);
}

function domainAnchor(domain: CatalogDomain): string {
  return `domain-${domain.prefix.toLowerCase()}`;
}

function renderIndex(catalog: Catalog): string {
  const rows = catalogRows(catalog);
  const out: string[] = [
    banner(catalog.source),
    '',
    '# Diagnostics',
    '',
    'Holotype reports every fallback, approximation and failure as a diagnostic with a stable code.',
    'Search this page for the code shown in the report, the plugin or the CLI output.',
    'Each code links to its own page with what happened, what to do and where the behaviour is specified.',
    '',
    `${rows.length} codes in ${catalog.domains.length} areas. Severities:`,
    '',
    '- **info**: a lossless choice worth knowing about. Usually nothing to do.',
    '- **warning**: a visible approximation. The result differs from the code in a way you can see.',
    '- **error**: a component or variant was not produced, or was produced incorrectly.',
    '',
    `The source of truth is the [diagnostics catalog](${planLink(sourceFile(catalog.source), 'diagnostics')}) in the design notes.`,
    '',
    '## Areas',
    '',
    ...catalog.domains.map(
      (domain) => `- [${domain.title} (\`${domain.prefix}_\`)](#${domainAnchor(domain)}): ${domain.rows.length}`,
    ),
  ];
  for (const domain of catalog.domains) {
    out.push(
      '',
      `<a id="${domainAnchor(domain)}"></a>`,
      '',
      `## ${domain.title} (\`${domain.prefix}_\`)`,
      '',
      ...domain.notes.flatMap((note) => [inline(note, catalog.source), '']),
      '| Code | Severity | What happened | What to do |',
      '|---|---|---|---|',
      ...domain.rows.map(
        (row) =>
          `| <a id="${row.code}"></a>[\`${row.code}\`](${row.code}.md) | ${severityLabel(row)} | ${cell(row.meaningMarkdown, catalog.source)} | ${cell(row.remedyMarkdown, catalog.source)} |`,
      ),
    );
  }
  out.push('');
  return out.join('\n');
}

/** A table cell's markdown as a sentence, still inside a table. */
function cell(markdown: string, source: string): string {
  return asSentence(inline(markdown, source));
}

/** A table cell's markdown as a sentence in running text. */
function prose(markdown: string, source: string): string {
  return asSentence(inline(unescapeCell(markdown), source));
}

/** Markdown from the plan, made safe and linkable from {@link DOCS_DIR}. */
function inline(markdown: string, source: string): string {
  return rebasePlanLinks(escapeHtml(markdown), sourceFile(source), PLAN_FROM_DOCS);
}

/** A design-notes chapter as a link named by its title, e.g. `[Capture engine](…)`. */
function chapterLink(file: string, chapter: string, titles: ChapterTitles, anchor?: string): string {
  return `[${titles.get(file) ?? `Chapter ${chapter}`}](${planLink(file, anchor)})`;
}

function severityLabel(row: CatalogRow): string {
  const label = SEVERITY_LABEL[row.severity];
  return row.severityNote ? `${label} (${row.severityNote})` : label;
}

function renderCodePage(row: CatalogRow, domain: CatalogDomain, source: string, titles: ChapterTitles): string {
  const { chapter, file, anchor } = row.definedIn;
  return [
    banner(source),
    '',
    `# \`${row.code}\``,
    '',
    '| | |',
    '|---|---|',
    `| Severity | ${severityLabel(row)} |`,
    `| Area | [${domain.title} (\`${domain.prefix}_\`)](${DOCS_INDEX}#${domainAnchor(domain)}) |`,
    `| Reported by | ${inline(row.emittedByMarkdown, source)} |`,
    '',
    '## What happened',
    '',
    prose(row.meaningMarkdown, source),
    '',
    '## What to do',
    '',
    prose(row.remedyMarkdown, source),
    '',
    '## Where it is defined',
    '',
    `- Behaviour: ${chapterLink(file, chapter, titles, anchor)} (design notes).`,
    `- Catalog entry: [Diagnostics catalog](${planLink(sourceFile(source), 'diagnostics')}) (design notes).`,
    `- All codes: [diagnostics index](${DOCS_INDEX}#${row.code}).`,
    '',
  ].join('\n');
}
