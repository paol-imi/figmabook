import { asSentence, toPlainText } from './markdown.ts';
import { type Catalog, type CatalogRow, catalogRows } from './model.ts';
import { PLAN_DIR } from './paths.ts';

/** Where the generated module lives, repository-relative. */
export const CATALOG_MODULE_PATH = 'packages/shared/src/diagnostics/catalog.generated.ts';

const LINE_WIDTH = 120;
const INDENT = '  ';

/**
 * Renders `catalog.generated.ts`: the typed code union and per-code metadata. The output is
 * deterministic (catalog order, no clock) and already in the repository's Biome format, so
 * `pnpm lint` passes on it unchanged.
 */
export function renderCatalogModule(catalog: Catalog): string {
  const rows = catalogRows(catalog);
  const emitters = [...new Set(rows.flatMap((row) => row.emittedBy))].sort(compareCodeUnits);
  const out: string[] = [
    `// Generated by tools/diag-gen from ${catalog.source}#diagnostics (12 §6.2).`,
    '// Do not edit: change the catalog in the plan, then run `pnpm diag:gen`.',
    '',
    '/** Code prefixes, one per catalog domain, in catalog order. */',
    ...constArray(
      'DIAGNOSTIC_DOMAINS',
      catalog.domains.map((domain) => domain.prefix),
    ),
    '',
    'export type DiagnosticDomain = (typeof DIAGNOSTIC_DOMAINS)[number];',
    '',
    '/** Domain names, as the catalog headings give them. */',
    'export const DIAGNOSTIC_DOMAIN_TITLES: { readonly [D in DiagnosticDomain]: string } = {',
    ...catalog.domains.map((domain) => property(INDENT, domain.prefix, quote(domain.title))),
    '};',
    '',
    '/** Packages (and tools) that raise catalog codes (the **Emitted by** column). */',
    ...constArray('DIAGNOSTIC_EMITTERS', emitters),
    '',
    'export type DiagnosticEmitter = (typeof DIAGNOSTIC_EMITTERS)[number];',
    '',
    '/** Every catalog code, in catalog order. Codes are API: never renamed, only deprecated. */',
    ...constArray(
      'DIAGNOSTIC_CODES',
      rows.map((row) => row.code),
    ),
    '',
    '/** A registered diagnostic code (12 §6.2). */',
    'export type DiagnosticCode = (typeof DIAGNOSTIC_CODES)[number];',
    '',
    '/** The plan chapter that specifies a code’s behaviour. */',
    'export interface DiagnosticChapterRef {',
    '  /** Chapter number, e.g. `03`. */',
    '  readonly chapter: string;',
    '  /** Repository-relative path of the chapter. */',
    '  readonly path: string;',
    '  /** Section anchor inside the chapter. */',
    '  readonly anchor?: string;',
    '}',
    '',
    '/** One catalog row. */',
    'export interface DiagnosticCatalogEntry<C extends DiagnosticCode = DiagnosticCode> {',
    '  readonly code: C;',
    '  readonly domain: DiagnosticDomain;',
    "  /** Default severity. The catalog's *warning* is `'warn'`. */",
    "  readonly severity: 'info' | 'warn' | 'error';",
    '  /** Qualifier of the severity, e.g. `error over 8 MB`. */',
    '  readonly severityNote?: string;',
    '  readonly emittedBy: readonly DiagnosticEmitter[];',
    '  /** What happened, in plain words (the **Meaning** column). */',
    '  readonly message: string;',
    '  /** What the user can do, in plain words (the **User remedy** column, D-40). */',
    '  readonly remedy: string;',
    '  readonly definedIn: DiagnosticChapterRef;',
    '}',
    '',
    '/** Metadata of every catalog code. */',
    'export const DIAGNOSTIC_CATALOG: { readonly [C in DiagnosticCode]: DiagnosticCatalogEntry<C> } = {',
    ...rows.flatMap((row) => entry(row)),
    '};',
    '',
  ];
  return out.join('\n');
}

function entry(row: CatalogRow): string[] {
  const inner = INDENT.repeat(2);
  const { chapter, file, anchor } = row.definedIn;
  const ref = [`chapter: ${quote(chapter)}`, `path: ${quote(`${PLAN_DIR}/${file}`)}`];
  if (anchor) ref.push(`anchor: ${quote(anchor)}`);
  return [
    `${INDENT}${row.code}: {`,
    property(inner, 'code', quote(row.code)),
    property(inner, 'domain', quote(row.domain)),
    property(inner, 'severity', quote(row.severity)),
    ...(row.severityNote ? [property(inner, 'severityNote', quote(row.severityNote))] : []),
    ...inlineOrBlock(`${inner}emittedBy: [`, row.emittedBy.map(quote), '],', inner),
    property(inner, 'message', quote(asSentence(toPlainText(row.meaningMarkdown)))),
    property(inner, 'remedy', quote(asSentence(toPlainText(row.remedyMarkdown)))),
    ...inlineOrBlock(`${inner}definedIn: {`, ref, '},', inner, true),
    `${INDENT}},`,
  ];
}

/** `key: value,`, moving the value to its own line when the line is too long (as Biome does). */
function property(indent: string, key: string, value: string): string {
  const line = `${indent}${key}: ${value},`;
  return line.length <= LINE_WIDTH ? line : `${indent}${key}:\n${indent}${INDENT}${value},`;
}

function constArray(name: string, items: readonly string[]): string[] {
  return inlineOrBlock(`export const ${name} = [`, items.map(quote), '] as const;', '');
}

/** An array or object literal on one line when it fits, else one item per line. */
function inlineOrBlock(
  open: string,
  items: readonly string[],
  close: string,
  indent: string,
  spaced = false,
): string[] {
  const pad = spaced ? ' ' : '';
  const inline = `${open}${pad}${items.join(', ')}${pad}${close}`;
  if (inline.length <= LINE_WIDTH) return [inline];
  return [open, ...items.map((item) => `${indent}${INDENT}${item},`), `${indent}${close}`];
}

/** A string literal the way Biome prints it: single quotes unless that needs more escapes. */
export function quote(value: string): string {
  const singles = value.split("'").length - 1;
  const doubles = value.split('"').length - 1;
  const mark = doubles < singles ? '"' : "'";
  const escaped = value
    .replaceAll('\\', '\\\\')
    .replaceAll(mark, `\\${mark}`)
    .replaceAll('\n', '\\n')
    .replaceAll('\r', '\\r')
    .replaceAll('\t', '\\t');
  return `${mark}${escaped}${mark}`;
}

/** Locale-independent ordering, so output is the same on every machine. */
export function compareCodeUnits(a: string, b: string): number {
  if (a === b) return 0;
  return a < b ? -1 : 1;
}
